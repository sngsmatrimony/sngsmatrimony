// Years for date of birth (18-90 years old)
export const YEARS = (() => {
  const currentYear = new Date().getFullYear();
  const minYear = currentYear - 90;
  const maxYear = currentYear - 18;
  const years = [];
  for (let year = maxYear; year >= minYear; year--) {
    years.push(year);
  }
  return years;
})();

